"""Bounded source-size warnings. Ruff remains the cyclomatic-complexity owner."""

import ast
import fnmatch
import io
import os
import re
import tokenize
from pathlib import Path

from .models import CheckConfig
from .models import CheckResult
from .models import Issue
from .models import Severity


def excluded(path: Path, patterns: list[str]) -> bool:
    """Match path components/globs without excluding unrelated substrings."""
    parts = path.as_posix().split("/")
    candidates = ["/".join(parts[start:end]) for start in range(len(parts)) for end in range(start + 1, len(parts) + 1)]
    for pattern in patterns:
        if pattern.endswith("/**"):
            pattern = pattern[:-3]
        if any(fnmatch.fnmatch(candidate, pattern) for candidate in candidates):
            return True
    return False


def notice(path: str, code: str, message: str, *, line: int = 1, end_line: int | None = None) -> Issue:
    return Issue(
        file=path,
        line=line,
        column=1,
        code=code,
        message=message,
        severity=Severity.INFO if code == "STRUCTURE-EXCLUDED" else Severity.WARNING,
        source="structure",
        end_line=end_line,
    )


def _generated_header(content: str) -> bool:
    """Recognize generated comments, never text embedded in an authored string."""
    try:
        for token in tokenize.generate_tokens(io.StringIO(content).readline):
            if token.start[0] > 10:
                break
            if token.type == tokenize.COMMENT and re.search(
                r"\b(?:automatically generated|generated by)\b", token.string, re.I
            ):
                return True
    except (tokenize.TokenError, IndentationError):
        # The AST pass reports syntax failures; this is only header recognition.
        pass
    return False


def check_source(content: str, filename: str, config: CheckConfig) -> CheckResult:
    """Count physical lines and independent AST function spans, never execute code."""
    result = CheckResult(files_checked=1, checks_run=["structure"])
    if excluded(Path(filename), config.exclude_patterns + config.structure_exclude_patterns):
        result.files_checked = 0
        result.issues.append(
            notice(filename, "STRUCTURE-EXCLUDED", "Structure analysis excluded by path configuration.")
        )
        return result
    if len(content) > config.structure_max_bytes or len(content.encode("utf-8")) > config.structure_max_bytes:
        result.files_checked = 0
        result.issues.append(
            notice(filename, "STRUCTURE-SKIPPED", "Structure analysis skipped: source exceeds byte limit.")
        )
        return result
    lines = content.splitlines()
    if _generated_header(content):
        result.files_checked = 0
        result.issues.append(
            notice(filename, "STRUCTURE-EXCLUDED", "Structure analysis excluded: generated-source header.")
        )
        return result
    if len(lines) > config.max_file_lines:
        result.issues.append(
            notice(
                filename,
                "FILE-LENGTH",
                f"File has {len(lines)} physical lines (warning threshold {config.max_file_lines}); review its responsibilities.",
            )
        )
    try:
        tree = ast.parse(content, filename=filename)
    except (SyntaxError, ValueError, RecursionError) as error:
        result.issues.append(
            notice(
                filename,
                "STRUCTURE-SKIPPED",
                f"Function analysis unavailable: {type(error).__name__}.",
                line=getattr(error, "lineno", None) or 1,
            )
        )
        return result
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
            span = (node.end_lineno or node.lineno) - node.lineno + 1
            if span > config.max_function_lines:
                result.issues.append(
                    notice(
                        filename,
                        "FUNCTION-LENGTH",
                        f"Function {node.name!r} spans {span} physical lines (warning threshold {config.max_function_lines}); review its responsibilities.",
                        line=node.lineno,
                        end_line=node.end_lineno,
                    )
                )
    return result


def check_paths(paths: list[str], config: CheckConfig) -> CheckResult:
    """Walk only explicitly requested directories, pruning excluded directories."""
    result = CheckResult(checks_run=["structure"])
    patterns = config.exclude_patterns + config.structure_exclude_patterns
    seen: set[Path] = set()

    def check_file(path: Path) -> None:
        resolved = path.resolve()
        if resolved in seen:
            return
        seen.add(resolved)
        if excluded(path, patterns):
            result.issues.append(
                notice(str(path), "STRUCTURE-EXCLUDED", "Structure analysis excluded by path configuration.")
            )
            return
        try:
            with path.open("rb") as source:
                raw = source.read(config.structure_max_bytes + 1)
            if len(raw) > config.structure_max_bytes:
                result.issues.append(
                    notice(str(path), "STRUCTURE-SKIPPED", "Structure analysis skipped: source exceeds byte limit.")
                )
                return
            encoding, _ = tokenize.detect_encoding(io.BytesIO(raw).readline)
            checked = check_source(raw.decode(encoding), str(path), config)
        except (OSError, UnicodeError, SyntaxError) as error:
            result.issues.append(
                notice(str(path), "STRUCTURE-SKIPPED", f"Structure analysis unavailable: {type(error).__name__}.")
            )
            return
        result.files_checked += checked.files_checked
        result.issues.extend(checked.issues)

    for name in paths:
        path = Path(name)
        if path.is_dir():
            if excluded(path, patterns):
                result.issues.append(
                    notice(str(path), "STRUCTURE-EXCLUDED", "Structure analysis excluded by path configuration.")
                )
                continue
            for directory, dirs, files in os.walk(path):
                dirs[:] = [name for name in dirs if not excluded(Path(directory) / name, patterns)]
                for name in files:
                    candidate = Path(directory) / name
                    if candidate.suffix in {".py", ".pyi"} and not excluded(candidate, patterns):
                        check_file(candidate)
        else:
            check_file(path)
    return result
