def test_config_loads_new_fields_and_explicit_selection(tmp_path, monkeypatch):
    project = tmp_path / "pyproject.toml"
    project.write_text(
        "[tool.amplifier-python-dev]\nenable_structure_check = false\nmax_file_lines = 700\n"
        'max_function_lines = 80\nstructure_max_bytes = 2048\nstructure_exclude_patterns = ["data/**"]\n'
    )
    loaded = load_config(project)
    assert not loaded.enable_structure_check
    assert (loaded.max_file_lines, loaded.max_function_lines, loaded.structure_max_bytes) == (700, 80, 2048)
    assert loaded.structure_exclude_patterns == ["data/**"]
    monkeypatch.setenv("AMPLIFIER_PYTHON_ENABLE_STRUCTURE_CHECK", "true")
    assert load_config(project).enable_structure_check
    assert not load_config(project, {"enable_structure_check": False}).enable_structure_check
    assert CheckConfig().enable_complexity_check
    assert not CheckConfig(enable_ruff_lint=False).enable_complexity_check
    assert CheckConfig(enable_ruff_lint=False, enable_complexity_check=True).enable_complexity_check
    assert CHECK_FLAGS["complexity"] == "enable_complexity_check"
    assert CHECK_FLAGS["structure"] == "enable_structure_check"


@pytest.mark.parametrize("field", ["max_file_lines", "max_function_lines", "structure_max_bytes"])
@pytest.mark.parametrize("value", [-2, 0, True, "100"])
def test_invalid_limits_fail_before_any_read(field, value, monkeypatch):
    monkeypatch.setattr(Path, "open", lambda *_args, **_kwargs: pytest.fail("invalid limits must never read"))
    with pytest.raises(ValueError, match=field):
        CheckConfig(**{field: value})
    with pytest.raises(ValueError, match=field):
        CheckConfig.from_dict({field: value})
