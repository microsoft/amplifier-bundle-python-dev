def config(**overrides):
    return CheckConfig(
        **{
            "enable_ruff_format": False,
            "enable_ruff_lint": False,
            "enable_pyright": False,
            "enable_stub_check": False,
            "enable_structure_check": True,
            "enable_complexity_check": False,
            **overrides,
        }
    )


def branches(count=12):
    return "def choose(value):\n" + "".join(f"    if value == {n}:\n        return {n}\n" for n in range(count))


def codes(result):
    return [issue.code for issue in result.issues]


def test_physical_lines_and_exact_threshold():
    source = "# comment\n\nx = 1\n"
    assert check_source(source, "small.py", config(max_file_lines=3)).clean
    result = check_source(source, "small.py", config(max_file_lines=2))
    assert codes(result) == ["FILE-LENGTH"]
    assert "3 physical lines" in result.issues[0].message
    assert result.success and result.issues[0].severity is Severity.WARNING


def test_ast_counts_nested_async_and_methods_once_without_comment_false_positives():
    source = (
        "# def pretend():\n"
        "class Example:\n"
        "    async def outer(self):\n"
        "        def inner():\n"
        "            x = 1\n"
        "            return x\n"
        "        return inner()\n"
        "    def short(self): return 1\n"
    )
    result = check_source(source, "nested.py", config(max_function_lines=2))
    assert [(issue.line, issue.end_line) for issue in result.issues] == [(3, 7), (4, 6)]
    assert all(issue.code == "FUNCTION-LENGTH" for issue in result.issues)


