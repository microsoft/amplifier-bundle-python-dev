def test_bounded_file_read_does_not_parse_partial_source(tmp_path, monkeypatch):
    path = tmp_path / "large.py"
    path.write_bytes(b"x = 1\n" * 100)
    reads = []
    original = Path.open

    class Observed(io.BytesIO):
        def read(self, size=-1):
            reads.append(size)
            return super().read(size)

    def open_file(self, *args, **kwargs):
        if self == path:
            return Observed(b"x = 1\n" * 100)
        return original(self, *args, **kwargs)

    monkeypatch.setattr(Path, "open", open_file)
    result = check_paths([str(path)], config(structure_max_bytes=20))
    assert reads == [21]
    assert codes(result) == ["STRUCTURE-SKIPPED"]
    assert result.files_checked == 0


