def test_lint_and_complexity_share_one_ruff_process(tmp_path, monkeypatch):
    path = tmp_path / "complex.py"
    path.write_text("import os\n" + branches())
    calls = []
    run = subprocess.run

    def observed(command, **kwargs):
        calls.append(command)
        return run(command, **kwargs)

    monkeypatch.setattr("amplifier_bundle_python_dev.checker.subprocess.run", observed)
    result = check_files([str(path)], config=config(enable_ruff_lint=True, enable_complexity_check=True))
    assert len(calls) == 1
    assert "C901" in codes(result) and "F401" in codes(result)
    assert "--extend-select" in calls[0]


def test_structure_exclusion_does_not_remove_ordinary_lint_coverage(tmp_path):
    path = tmp_path / "excluded.py"
    path.write_text("undefined_name\n" + branches())
    settings = {
        "enable_ruff_lint": True,
        "enable_structure_check": False,
        "structure_exclude_patterns": ["excluded.py"],
    }
    before = check_files([str(path)], config=config(**settings, enable_complexity_check=False))
    after = check_files([str(path)], config=config(**settings, enable_complexity_check=True))
    assert "F821" in codes(before) and "F821" in codes(after)
    assert "C901" not in codes(after)


