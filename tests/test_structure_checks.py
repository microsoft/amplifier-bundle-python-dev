def test_directory_walk_prunes_exclusions_and_file_calls_never_walk(tmp_path, monkeypatch):
    (tmp_path / "vendor").mkdir()
    (tmp_path / "vendor" / "large.py").write_text("x=1\n" * 5)
    authored = tmp_path / "authored.py"
    authored.write_text("x=1\n" * 5)
    result = check_paths([str(tmp_path)], config(max_file_lines=2))
    assert [Path(issue.file).name for issue in result.issues] == ["authored.py"]
    monkeypatch.setattr(
        "amplifier_bundle_python_dev.structure.os.walk", lambda *_: pytest.fail("single file must not walk")
    )
    assert codes(check_files([str(authored)], config=config(max_file_lines=2))) == ["FILE-LENGTH"]


def test_c901_only_is_a_warning_and_retains_native_threshold(tmp_path):
    path = tmp_path / "complex.py"
    path.write_text(branches())
    project = tmp_path / "pyproject.toml"
    project.write_text("[tool.ruff.lint.mccabe]\nmax-complexity = 20\n")
    settings = config(enable_structure_check=False, enable_complexity_check=True)
    assert check_files([str(path)], config=settings).clean
    project.write_text("[tool.ruff.lint.mccabe]\nmax-complexity = 2\n")
    result = check_files([str(path)], config=settings)
    assert codes(result) == ["C901"]
    assert result.success and result.issues[0].severity is Severity.WARNING
    assert "(13 > 2)" in result.issues[0].message


