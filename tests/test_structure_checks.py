def test_generated_header_and_encoding(tmp_path):
    generated = check_source(
        "# Automatically generated by schema-tool\n" + "x=1\n" * 5, "schema.py", config(max_file_lines=2)
    )
    assert codes(generated) == ["STRUCTURE-EXCLUDED"]
    path = tmp_path / "encoded.py"
    path.write_bytes(b"# coding: latin-1\n# caf\xe9\nx = 1\n")
    assert check_paths([str(path)], config()).clean
    path.write_bytes(b"# coding: utf-8\n\xff\n")
    assert codes(check_paths([str(path)], config())) == ["STRUCTURE-SKIPPED"]


